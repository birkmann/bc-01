#[component]
pub fn Icon(#[prop(into)] name: Signal<String>, #[prop(optional, into)] class: Option<String>, #[prop(optional)] size: Option<u32>) -> impl IntoView {
    let cls = format!("icon {}", class.unwrap_or_default());
    let style = size.map(|s| format!("width:{s}px;height:{s}px"));
    view! {
        <svg class=cls viewBox="0 0 24 24" aria-hidden="true" style=style
            inner_html=move || icon_markup(&name.get())></svg>
    }
}
